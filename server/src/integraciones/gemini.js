// Vocabulario frecuente por idioma, para detectar en qué idioma llegó la respuesta.
const VOCABULARIO = {
  es: new Set(['el', 'la', 'de', 'que', 'y', 'en', 'los', 'las', 'un', 'una', 'es', 'para', 'con', 'por', 'se', 'del', 'su', 'al', 'lo']),
  en: new Set(['the', 'and', 'is', 'are', 'of', 'to', 'with', 'for', 'this', 'that', 'which', 'used', 'may', 'or', 'it', 'by', 'be', 'from']),
  fr: new Set(['le', 'les', 'des', 'et', 'est', 'un', 'une', 'pour', 'avec', 'qui', 'dans', 'du', 'au', 'sont', 'ce']),
  pt: new Set(['o', 'os', 'as', 'do', 'da', 'dos', 'das', 'e', 'é', 'um', 'uma', 'para', 'com', 'não', 'em', 'que', 'por']),
  de: new Set(['der', 'die', 'das', 'und', 'ist', 'nicht', 'mit', 'für', 'von', 'zu', 'ein', 'eine', 'den', 'dem', 'sich', 'auch']),
};

// Idioma detectado de un texto, o null si no hay suficientes pistas claras.
export function idiomaDetectado(texto) {
  const letras = texto.match(/\p{L}/gu) ?? [];
  const japones = texto.match(/[぀-ヿ一-龯]/gu)?.length ?? 0;
  if (japones >= 2 && japones >= letras.length * 0.3) return 'ja';

  const palabras = texto.toLowerCase().match(/\p{L}+/gu) ?? [];
  const puntos = Object.entries(VOCABULARIO)
    .map(([codigo, vocab]) => [codigo, palabras.filter((p) => vocab.has(p)).length])
    .sort((a, b) => b[1] - a[1]);
  const [mejor, segundo] = puntos;
  if (mejor[1] < 2 || mejor[1] === segundo[1]) return null;
  return mejor[0];
}

// true si el texto está en el idioma pedido, o si no hay pistas suficientes para saber otra cosa.
export function respuestaEnIdioma(texto, codigo) {
  const detectado = idiomaDetectado(texto);
  if (detectado === null) return true;
  const esperado = codigo === 'es-MX' ? 'es' : codigo;
  return detectado === esperado;
}

// Compatibilidad con la comprobación anterior (español de México).
export const esEspanol = (texto) => respuestaEnIdioma(texto, 'es-MX');

// El término se envía solo como dato del mensaje del usuario, entre comillas.
export function construirMensaje(termino) {
  return `Term: "${termino}"`;
}

// Diagnóstico para la consola del servidor. Elimina claves, URLs y textos largos; nunca registra cabeceras ni datos del usuario.
export function sanearDiagnostico(texto, apiKey = null) {
  let limpio = String(texto ?? '-');
  if (apiKey) limpio = limpio.split(apiKey).join('[clave]');
  return limpio
    .replace(/AIza[0-9A-Za-z_-]{10,}/g, '[clave]')
    .replace(/https?:\/\/\S+/g, '[url]')
    .slice(0, 200);
}

export function crearClienteGemini({ apiKey = null, modelo = MODELO_PREDETERMINADO, fetch: fetchFn = globalThis.fetch, ahora = () => Date.now() }) {
  // Un modelo retirado (p. ej. en GEMINI_MODELO de .env) no se usa: se aplica el predeterminado y se avisa en consola.
  if (MODELOS_RETIRADOS.has(modelo)) {
    console.warn(`[gemini] el modelo ${modelo} ya no está disponible para nuevos usuarios; se usa ${MODELO_PREDETERMINADO}. Actualiza GEMINI_MODELO.`);
    modelo = MODELO_PREDETERMINADO;
  }
  let pausaHasta = 0;
  let motivoPausa = null;
  const consultasPorUsuario = new Map(); // Solo en memoria: no se envía a Google.
  let contadorDia = { fecha: '', consultas: 0 };

  function pausar(duracionMs, motivo) {
    pausaHasta = ahora() + duracionMs;
    motivoPausa = motivo;
  }

  // Ventana de consultas de un usuario: solo las de la última hora. Reutiliza el mismo control de explicar().
  function ventanaUsuario(usuarioId, ahoraMs) {
    return (consultasPorUsuario.get(usuarioId) ?? []).filter((t) => ahoraMs - t < UNA_HORA_MS);
  }

  // Estado para la interfaz. Solo códigos y cifras; nunca la clave ni detalles de configuración.
  // Con usuarioId (de la sesión autenticada), incluye el límite personal de esa cuenta.
  function estado(usuarioId = null) {
    let base;
    if (!apiKey) base = { disponible: false, motivo: 'no_configurada' };
    else if (pausaHasta > ahora()) base = { disponible: false, motivo: motivoPausa };
    else base = { disponible: true, motivo: null };
    if (usuarioId === null) return base;

    const ahoraMs = ahora();
    const recientes = ventanaUsuario(usuarioId, ahoraMs);
    const restantes = Math.max(0, LIMITE_POR_USUARIO_HORA - recientes.length);
    const diarioAgotado = contadorDia.fecha === fechaDe(ahoraMs) && contadorDia.consultas >= LIMITE_GLOBAL_DIA;
    return {
      ...base,
      limite: {
        maximo: LIMITE_POR_USUARIO_HORA,
        restantes,
        reintentoEn: restantes === 0 ? reintentoDe(recientes) : null,
        diarioAgotado,
      },
    };
  }

  async function explicar(usuarioId, termino, idioma) {
    // Validación de entrada primero: no gasta cuota ni revela el estado de la función.
    const limpio = validarTerminoIa(termino);
    const codigo = validarIdioma(idioma);
    if (!estado().disponible) throw new ErrorApp(503, 'ia_no_disponible', NO_DISPONIBLE);

    const ahoraMs = ahora();
    const recientes = ventanaUsuario(usuarioId, ahoraMs);
    if (recientes.length >= LIMITE_POR_USUARIO_HORA) {
      throw new ErrorApp(
        429,
        'limite_alcanzado',
        'Has hecho muchas consultas de IA. Inténtalo más tarde.',
        null,
        { reintentoEn: reintentoDe(recientes) },
      );
    }
    const hoyClave = fechaDe(ahoraMs);
    if (contadorDia.fecha !== hoyClave) contadorDia = { fecha: hoyClave, consultas: 0 };
    if (contadorDia.consultas >= LIMITE_GLOBAL_DIA) {
      throw new ErrorApp(429, 'limite_alcanzado', 'La consulta de IA alcanzó su límite de hoy. Inténtalo mañana.');
    }

    // Se cuenta antes de llamar: también protege la cuota cuando una llamada falla.
    recientes.push(ahoraMs);
    consultasPorUsuario.set(usuarioId, recientes);
    contadorDia.consultas += 1;

    let respuesta;
    try {
      respuesta = await fetchFn(URL_MODELO(modelo), {
        method: 'POST',
        headers: { 'content-type': 'application/json', 'x-goog-api-key': apiKey },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: instruccionesPara(codigo) }] },
          contents: [{ role: 'user', parts: [{ text: construirMensaje(limpio) }] }],
          // Razonamiento mínimo y espacio suficiente: los tokens de razonamiento cuentan dentro de maxOutputTokens.
          generationConfig: { maxOutputTokens: 1024, temperature: 0.2, thinkingConfig: { thinkingLevel: 'minimal' } },
        }),
        signal: AbortSignal.timeout(TIMEOUT_MS),
      });
    } catch (fallo) {
      console.error(`[gemini] fallo de conexión: ${sanearDiagnostico(fallo?.name, apiKey)}`);
      throw new ErrorApp(503, 'ia_no_disponible', NO_DISPONIBLE);
    }

    // Diagnóstico: código HTTP de Google y su error (sin datos sensibles). Solo se registra; la respuesta no cambia.
    if (!respuesta.ok) {
      const cuerpoError = await respuesta.json().catch(() => null);
      const error = cuerpoError?.error ?? {};
      console.error(
        `[gemini] HTTP ${respuesta.status} código=${sanearDiagnostico(error.code, apiKey)} estado=${sanearDiagnostico(error.status, apiKey)} mensaje=${sanearDiagnostico(error.message, apiKey)}`,
      );
    }

    // 429: cuota agotada. Se pausa sin intentar ningún otro servicio.
    if (respuesta.status === 429) {
      pausar(SEIS_HORAS_MS, 'cuota_agotada');
      throw new ErrorApp(503, 'ia_no_disponible', NO_DISPONIBLE);
    }
    // 401/403: clave no válida. No tiene sentido reintentar con la misma clave.
    if (respuesta.status === 401 || respuesta.status === 403) {
      pausar(VEINTICUATRO_HORAS_MS, 'clave_no_valida');
      throw new ErrorApp(503, 'ia_no_disponible', NO_DISPONIBLE);
    }
    if (!respuesta.ok) throw new ErrorApp(503, 'ia_no_disponible', NO_DISPONIBLE);

    const datos = await respuesta.json().catch(() => null);
    const texto = datos?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (typeof texto !== 'string' || texto.trim() === '') {
      throw new ErrorApp(503, 'ia_no_disponible', 'No se pudo generar una explicación para ese término.');
    }
    // Nunca se muestra una respuesta en otro idioma: se rechaza con un mensaje en español.
    if (!respuestaEnIdioma(texto, codigo)) {
      throw new ErrorApp(503, 'ia_no_disponible', 'No se pudo generar la explicación en el idioma seleccionado. Inténtalo de nuevo.');
    }
    return { texto: texto.trim().slice(0, MAX_TEXTO_SALIDA), idioma: codigo, aviso: idiomaDe(codigo).aviso };
  }

  return { estado, explicar };
}
