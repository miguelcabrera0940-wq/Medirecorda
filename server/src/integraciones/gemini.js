// Explicación de términos farmacéuticos generales con Google Gemini (API del nivel gratuito).
// Documentación: https://ai.google.dev/gemini-api/docs
// Reglas:
//   * La clave vive solo en el servidor (variable GEMINI_API_KEY) y se envía en una cabecera, nunca en la URL.
//   * Solo se envían el término que escribe la persona y el código de idioma elegido. Nada de usuarios,
//     medicamentos registrados, horarios ni historial.
//   * El idioma de la respuesta es el elegido, aunque el término esté en otro idioma. Lista cerrada de idiomas.
//   * No hay alternativa de pago: si la cuota se agota o la clave no es válida, la función se pausa.
import { ErrorApp } from '../errores.js';

const URL_MODELO = (modelo) =>
  `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(modelo)}:generateContent`;
const TERMINO = /^[\p{L} .-]{2,40}$/u; // Sin números: así no entran dosis ni datos personales.
const TIMEOUT_MS = 15000;
const MAX_TEXTO_SALIDA = 1200;
const UNA_HORA_MS = 60 * 60 * 1000;
const SEIS_HORAS_MS = 6 * UNA_HORA_MS;
const VEINTICUATRO_HORAS_MS = 24 * UNA_HORA_MS;
const LIMITE_POR_USUARIO_HORA = 5;
const LIMITE_GLOBAL_DIA = 40;

// Momento en que vuelve a quedar libre un cupo: una hora después de la consulta más antigua de la ventana.
const reintentoDe = (recientes) => new Date(Math.min(...recientes) + UNA_HORA_MS).toISOString();
const fechaDe = (ahoraMs) => new Date(ahoraMs).toISOString().slice(0, 10);
const IDIOMA_PREDETERMINADO = 'es-MX';

// Modelo por defecto y modelos retirados para nuevos usuarios (Google responde 404 para ellos).
export const MODELO_PREDETERMINADO = 'gemini-3.5-flash-lite';
const MODELOS_RETIRADOS = new Set(['gemini-2.5-flash-lite']);

